// Variables
const name = "Deva";
let age = 21;

// Function
function add(a, b) {
    return a + b;
}

// Function call
const sum = add(10, 20);

// Output
console.log("Hello, " + name + "!");
console.log("Age:", age);
console.log("10 + 20 =", sum);

// Conditional
if (age >= 18) {
    console.log("You are an adult.");
} else {
    console.log("You are a minor.");
}

// Loop
for (let i = 1; i <= 5; i++) {
    console.log("Count:", i);
}
